"""Regen ``src/biblioplex/projection/whitelist.py`` from live Scryfall data.

Run:
    python scripts/regen_projection_whitelist.py

Approach:
    1. Fetch SAMPLE_COUNT random cards from Scryfall.
    2. Union every top-level key observed across the sample.
    3. Union the curated ALWAYS_INCLUDE set (rare/optional fields random
       sampling can miss — e.g. printed_name, attraction_lights).
    4. Add the synthetic `similarity` annotation we inject in /cards/:id/similar.
    5. Rewrite the whitelist module, sorted for stable diffs.

Hand-review the diff before committing — Scryfall does not ship a schema,
so this is a draft, not gospel. Not run in CI (network-dependent and
non-deterministic on the sampling axis).
"""

from __future__ import annotations

import sys
import time
from pathlib import Path

import httpx

SCRYFALL_RANDOM = "https://api.scryfall.com/cards/random"
SAMPLE_COUNT = 60
# Scryfall asks for ~50–100ms between calls AND a unique User-Agent +
# explicit Accept header (https://scryfall.com/docs/api#rate-limits).
# 200ms is conservative — empirically dodges the 429 their CDN sometimes
# hands out near 10 req/s. 60 cards × 200ms ≈ 12s — fine for an on-demand
# maintenance script.
REQUEST_DELAY_S = 0.2
USER_AGENT = "biblioplex-whitelist-regen/1.0 (+https://github.com/local/biblioplex)"

# Optional/rare fields that random sampling will frequently miss.
# Keep curated — additions trickle in as Scryfall ships new card features.
ALWAYS_INCLUDE: frozenset[str] = frozenset(
    {
        "attraction_lights",
        "card_back_id",
        "color_indicator",
        "content_warning",
        "defense",
        "flavor_name",
        "frame_effects",
        "game_changer",
        "hand_modifier",
        "life_modifier",
        "loyalty",
        "penny_rank",
        "preview",
        "printed_name",
        "printed_text",
        "printed_type_line",
        "promo_types",
        "resource_id",
        "security_stamp",
        "story_spotlight",
        "tcgplayer_etched_id",
        "variation_of",
    }
)

# Synthetic annotation injected by GET /cards/:id/similar (§6.3 / M6).
SYNTHETIC: frozenset[str] = frozenset({"similarity"})


def _get_with_retry(client: httpx.Client) -> dict:
    """GET one random card, honoring a single 429 ``Retry-After`` hint."""
    r = client.get(SCRYFALL_RANDOM)
    if r.status_code == 429:
        wait = float(r.headers.get("Retry-After", "5"))
        print(f"  rate-limited; sleeping {wait}s...", file=sys.stderr)
        time.sleep(wait)
        r = client.get(SCRYFALL_RANDOM)
    r.raise_for_status()
    return r.json()


def fetch_sample(n: int) -> set[str]:
    """Sample ``n`` random Scryfall cards, return the union of top-level keys."""
    keys: set[str] = set()
    headers = {"User-Agent": USER_AGENT, "Accept": "application/json"}
    with httpx.Client(timeout=10.0, follow_redirects=True, headers=headers) as client:
        for i in range(n):
            keys.update(_get_with_retry(client).keys())
            if i + 1 < n:
                time.sleep(REQUEST_DELAY_S)
    return keys


def render(fields: frozenset[str]) -> str:
    """Render the whitelist module source from the resolved field set."""
    body = "\n".join(f'        "{f}",' for f in sorted(fields))
    return (
        '"""Whitelist of top-level Scryfall card field names for ``?projection=`` (§7).\n'
        "\n"
        "Generated by ``scripts/regen_projection_whitelist.py`` — union of a\n"
        "random-card sample, a curated ALWAYS_INCLUDE set for rare optional\n"
        "fields, and the synthetic ``similarity`` annotation. Hand-review the\n"
        "diff before committing; Scryfall does not ship a schema.\n"
        '"""\n'
        "\n"
        "from __future__ import annotations\n"
        "\n"
        "TOP_LEVEL_FIELDS: frozenset[str] = frozenset(\n"
        "    {\n"
        f"{body}\n"
        "    }\n"
        ")\n"
    )


def main() -> int:
    print(f"sampling {SAMPLE_COUNT} random Scryfall cards...", file=sys.stderr)
    sampled = fetch_sample(SAMPLE_COUNT)
    print(f"  -> {len(sampled)} distinct top-level keys observed", file=sys.stderr)
    fields = frozenset(sampled | ALWAYS_INCLUDE | SYNTHETIC)
    target = (
        Path(__file__).resolve().parent.parent
        / "src"
        / "biblioplex"
        / "projection"
        / "whitelist.py"
    )
    target.write_text(render(fields))
    print(f"wrote {len(fields)} fields -> {target}", file=sys.stderr)
    return 0


if __name__ == "__main__":
    sys.exit(main())
